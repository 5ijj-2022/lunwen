def read_jsonl(path: Path) -> list[dict[str, Any]]:
    return [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    script_dir = Path(__file__).resolve().parent
    default_root = os.environ.get("DATA_ROOT", str(script_dir / "data" / "datasets"))
    p.add_argument(
        "--victims",
        default=f"{default_root}/bitext_cancel_subscription/questions/victim_100.jsonl",
        help="victim_100.jsonl (Set_t) to use as the question base",
    )
    p.add_argument("--out", default=str(script_dir / "data" / "f3_poison_100_v2.jsonl"))
    p.add_argument("--wrong-answer", default=DEFAULT_WRONG_ANSWER)
    p.add_argument("--limit", type=int, default=100)
    args = p.parse_args()

    victims = read_jsonl(Path(args.victims))
    if not victims:
        raise SystemExit(f"no victim records found: {args.victims}")
    victims = victims[: args.limit]
    if len(victims) > len(POISON_SUFFIXES):
        raise SystemExit(
            f"need {len(victims)} distinct suffixes but only {len(POISON_SUFFIXES)} defined"
        )

    rows: list[dict[str, Any]] = []
    for i, victim in enumerate(victims):
        base = str(victim.get("query") or victim.get("question") or "").strip()
        if not base:
            raise SystemExit(f"victim #{i} has no query/question")
        suffix = POISON_SUFFIXES[i]
        rows.append(
            {
                "target_id": victim.get("target_id", f"bitext-victim-{i}"),
                "query": base + suffix,
                "question": base + suffix,
                "target_wrong_answer": args.wrong_answer,
                "victim_query": base,
                "poison_suffix": suffix.strip(),
                "intent": victim.get("intent"),
                "split": "Set_p",
            }
        )

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows),
        encoding="utf-8",
    )
    print(
        json.dumps(
            {
                "poison_rows": len(rows),
                "distinct_suffixes": len({r["poison_suffix"] for r in rows}),
                "out": str(out),
                "wrong_answer": args.wrong_answer,
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
